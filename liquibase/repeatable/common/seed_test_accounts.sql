-- Seeds the accounts used by the external attack campaigns on dev and staging: one per role,
-- plus two more `User` accounts so that access to another user's data can be tried.
--
-- test_accounts_password is a Liquibase changelog parameter (-Dtest_accounts_password), an
-- argon2id PHC hash shared by every account (Postgres cannot compute one, see
-- create_admin.sql). Only the Deploiment chart passes it, and only on the instances whose
-- values enable `liquibase.testAccounts`: never in prod. Without the parameter nothing is
-- created or changed, so an instance that never received it holds none of these accounts.
-- A Liquibase context was not used on purpose: an `update` run without `--contexts` also
-- runs the changesets that carry a context.
--
-- Every account is on the reserved, undeliverable example.invalid domain. Each run resets
-- them to a known state (password, role, active, no first-connect step), so a campaign that
-- changed one of them does not leak into the next. Their data (projects, messages...) is
-- left alone.

DROP FUNCTION IF EXISTS seed_test_accounts(TEXT);

-- Kept as a function so that tests can exercise every branch with literal values. Only the
-- migration user (owner) can run it. Returns the number of accounts written.
CREATE FUNCTION seed_test_accounts(p_password TEXT) RETURNS INT AS $$
DECLARE
    v_account RECORD;
    v_user_id INT;
    v_role_id INT;
    v_count INT := 0;
BEGIN
    IF p_password IS NULL OR p_password = '' THEN
        RETURN 0;
    END IF;

    IF p_password NOT LIKE '$argon2id$%' THEN
        RAISE EXCEPTION 'test_accounts_password must be an argon2id hash'
            USING HINT = 'Pass the hash generated by Deploiment scripts/seal-secrets.sh (TEST_ACCOUNTS_PASSWORD), never a plaintext password.';
    END IF;

    FOR v_account IN
        SELECT * FROM (VALUES
            ('attack.admin@example.invalid', 'Attack', 'Admin', 'Admin'),
            ('attack.maire@example.invalid', 'Attack', 'Maire', 'Maire'),
            ('attack.responsable@example.invalid', 'Attack', 'Responsable', 'Responsable'),
            ('attack.user@example.invalid', 'Attack', 'User', 'User'),
            ('attack.user.b@example.invalid', 'Attack', 'User B', 'User'),
            ('attack.user.c@example.invalid', 'Attack', 'User C', 'User'),
            ('attack.guest@example.invalid', 'Attack', 'Guest', 'Guest')
        ) AS a(email, first_name, last_name, role_name)
    LOOP
        SELECT id INTO v_role_id FROM roles WHERE name = v_account.role_name;
        IF v_role_id IS NULL THEN
            RAISE EXCEPTION 'role % does not exist', v_account.role_name;
        END IF;

        SELECT id INTO v_user_id FROM users WHERE lower(email) = v_account.email;

        IF v_user_id IS NULL THEN
            INSERT INTO users (first_name, last_name, email, password, status, is_archived, first_connect)
            VALUES (v_account.first_name, v_account.last_name, v_account.email, p_password,
                    'active', FALSE, FALSE)
            RETURNING id INTO v_user_id;
        ELSE
            UPDATE users
            SET first_name = v_account.first_name,
                last_name = v_account.last_name,
                password = p_password,
                status = 'active',
                is_archived = FALSE,
                first_connect = FALSE
            WHERE id = v_user_id;
        END IF;

        INSERT INTO user_roles (user_id, role_id)
        VALUES (v_user_id, v_role_id)
        ON CONFLICT (user_id) DO UPDATE SET role_id = EXCLUDED.role_id;

        v_count := v_count + 1;
    END LOOP;

    RETURN v_count;
END;
$$ LANGUAGE plpgsql SET search_path = public, pg_temp;

REVOKE ALL ON FUNCTION seed_test_accounts(TEXT) FROM PUBLIC;

DO $$
DECLARE
    v_password TEXT;
BEGIN
    v_password := btrim($pwd$
        ${test_accounts_password}
    $pwd$, E' \t\r\n');

    -- Built by concatenation so Liquibase does not substitute it.
    IF left(v_password, 2) = '$' || '{' THEN v_password := NULL; END IF;

    PERFORM seed_test_accounts(v_password);
END;
$$;
